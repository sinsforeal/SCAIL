"""What a feeling about another person is made of, before it has a name.

The spec is `docs/primitives.md`; this is step 1 and 2 of its §7. Nothing in
the running loop reads it yet.

The problem it exists for, measured: 4,517 lines of `sim/` need a relation to
exist before they mean anything, against 1,898 that do not, so a character who
starts at zero reads about seventy per cent of her own psychology as empty
files. And what she does read is wrong rather than empty --
`yukarin/tools/zero_probe.py` shows a relational gauge with no cause starting
at its baseline, so on her first tick she is moderately lonely about a man she
has not met and carrying ten points of guilt toward him. Nothing caused any of
it.

Six quantities instead, three of them two-sided because a stranger is
asymmetric by construction, and nine numbers in all. **Zero means zero.** A
relational quantity has no baseline: a baseline is where something rests when
nothing is happening, and there is no rest state for a history that does not
exist. Baselines belong to the body and the emotions, which she has alone in
an empty room.

The named mechanisms -- attachment, closeness, longing, guilt, resentment,
tension, the ick, withholding, rupture -- stop holding state and become
readings of these. Each is then quiet at zero for a reason that can be
stated rather than because its file is empty, and the arc from stranger to
companion is generated by the same events that generate everything else.

**No write without a reason.** `move()` refuses an empty `why`, and every
write keeps what caused it, so any number here can be traced back to the thing
that produced it. That is the whole difference between this and the
hand-written 62 in `data/cast.json` which no event ever earned.

kv `primitives`: {person: {key: value, ..., "_log": [{ts, key, from, to, why}]}}
"""

import logger
from sim import lang

# The nine. Two-sided ones carry the direction in the name, and the direction
# is always written from her side: `_hers` is what she has of him, `_his` is
# what she believes he has of her.
KEYS = (
    "attention_hers",        # how much of her thinking he occupies when absent
    "attention_his",         # how much of hers she believes she occupies of his
    "predictability_hers",   # how well she can call what he does next
    "exposure_hers",         # how much of him she has seen
    "exposure_his",          # how much of her he has seen
    "reciprocity",           # signed: positive is in her favour, negative in his
    "cost_of_loss",          # what his disappearing would actually take
    "threat",                # whether he can damage her
)
SIGNED = ("reciprocity",)
# Exposure is a ratchet. What has been seen cannot be unseen, so it has no
# decay term at all, and that is deliberate rather than an omission: it is
# what makes the opening condition of a character who has been read to the
# bottom irreversible.
NO_DECAY = ("exposure_hers", "exposure_his")

THREAT_KINDS = ("exposure", "reach", "standing")


def effort_units(text):
    """How much of herself a message cost, in units comparable across scripts.

    Both sides of the ledger measured this as `len(text.split())`, and Japanese
    is not written with spaces. Every reply the second character wrote counted
    as one or two words however long it was: 「どう思うって… わかんない。読んじゃった
    こと、ちょっと後悔してる。」 scored 2 against 14 for the same sentence in
    English, so answering him credited 0.20 where it should have credited about
    1.40. Her ledger drifted DOWN across her whole first conversation -- from
    -70.0 to -70.3 -- while she answered every message he sent. His side was
    wrong the same way, because he writes to her in Japanese.

    So: words for a script that has them, and for kana and kanji a count of
    characters over the average length of a Japanese morpheme. Punctuation and
    the quotation brackets fall outside both ranges and are not counted, which
    is right -- 「」 is not effort.
    """
    s = str(text or "")
    cjk = sum(1 for ch in s
              if "぀" <= ch <= "ヿ" or "一" <= ch <= "鿿")
    words = sum(1 for t in s.split()
                if not any("぀" <= ch <= "ヿ" or "一" <= ch <= "鿿" for ch in t))
    return words + cjk / 2.2


def _clamp(v, lo, hi):
    return max(lo, min(hi, v))


class Primitives:
    def __init__(self, config, store, clock):
        self.config = config
        self.store = store
        self.clock = clock
        self._level_once()

    def _level_once(self):
        """One-shot at the correction of the ledger's credit side (his call,
        2026-09-04): the old arithmetic credited every answer of hers as a
        gift, and the second character's ledger with him had walked from its
        seed of -70 to +84 in three days. A ledger in credit is set back to
        level once, with a reason, through `move` so the correction is in the
        primitives' own log like everything else; kv `primitives_levelled`
        marks it done so a restart does not do it twice. The save of a
        character with no ledger in credit only gets the mark."""
        try:
            if self.store.get("primitives_levelled"):
                return
            for person, r in list(self._all().items()):
                now = float((r or {}).get("reciprocity", 0) or 0)
                if now > 0:
                    self.move(person, "reciprocity", -now,
                              "the ledger was crediting an answer as a gift; it is set back to level and "
                              "starts again from what actually goes unanswered", cause="corrected")
                    logger.log(f"[primitives] the ledger with {person} levelled: {now:.1f} -> 0")
            self.store.set("primitives_levelled", self.clock.now_ts())
        except Exception as e:
            logger.log(f"[primitives] the ledger was not levelled: {type(e).__name__}: {e}")

    # ---------------- the store ----------------
    def _all(self):
        rows = dict(self.store.get("primitives", {}) or {})
        # a local rebound to a schedule-block key wrote nineteen "people"
        # named like 2026-09-02|11:00 into the second character's save; a
        # person key never carries a bar, so they are dropped at first sight
        ghosts = [k for k in rows if "|" in str(k)]
        if ghosts:
            for k in ghosts:
                rows.pop(k, None)
            self.store.set("primitives", rows)
            logger.log(f"[primitives] dropped {len(ghosts)} phantom row(s) keyed like a schedule block")
        return rows

    def row(self, person):
        r = dict(self._all().get(person) or {})
        for k in KEYS:
            r.setdefault(k, 0.0)
        r.setdefault("threat_kinds", [])
        r.setdefault("_log", [])
        return r

    def get(self, person, key):
        return float(self.row(person).get(key, 0.0))

    def move(self, person, key, amount, why, cause=""):
        """The only way a number changes. `why` is required: a relational
        quantity with no cause is exactly the thing this module exists to stop
        being possible."""
        if key not in KEYS:
            raise KeyError("not a primitive: %s" % key)
        if not str(why or "").strip():
            raise ValueError("a primitive never moves without a reason (%s.%s)" % (person, key))
        c = self.config.primitives
        rows = self._all()
        r = self.row(person)
        lo = -c.ceiling if key in SIGNED else 0.0
        before = float(r.get(key, 0.0))
        after = _clamp(before + float(amount), lo, c.ceiling)
        if after == before:
            return before
        r[key] = after
        log = list(r.get("_log") or [])
        log.append({"ts": self.clock.now_ts(), "key": key,
                    "from": round(before, 1), "to": round(after, 1),
                    "why": str(why)[:160], "cause": str(cause)[:80]})
        r["_log"] = log[-c.log_rows:]
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] %s %s %.0f -> %.0f (%s)" % (person, key, before, after, str(why)[:80]))
        return after

    def decay(self, person, hours):
        """Time passing, which is not the same as nothing happening. Exposure
        does not decay; reciprocity drifts toward zero because people do
        forgive a ledger; the rest fade toward nothing, never toward a rest
        value, because there is no rest value for a history."""
        if hours <= 0:
            return
        c = self.config.primitives
        rows = self._all()
        r = self.row(person)
        changed = False
        for k in KEYS:
            if k in NO_DECAY:
                continue
            v = float(r.get(k, 0.0))
            if not v:
                continue
            rate = float(getattr(c.decay_per_hour, k, 0.0) if hasattr(c.decay_per_hour, k)
                         else (c.decay_per_hour.get(k, 0.0) if isinstance(c.decay_per_hour, dict) else 0.0))
            if not rate:
                continue
            step = rate * hours
            nv = max(0.0, v - step) if v > 0 else min(0.0, v + step)
            # What he has actually done does not decay. A demonstrated use of
            # what he holds of her puts a floor under the threat, and time
            # passing is not evidence against it.
            floor = float((r.get("_floors") or {}).get(k, 0.0))
            if floor and nv < floor:
                nv = min(v, floor)
            if nv != v:
                r[k] = nv
                changed = True
        if changed:
            rows[person] = r
            self.store.set("primitives", rows)

    def accrue(self, person, hours):
        """What he has quietly become load-bearing for.

        Cost of loss is the one that cannot be set and cannot be moved in a
        day: it is the integral of the others. Nobody writes it, because
        nobody decides it -- it is what has built up while she was carrying
        him around, and it is why leaving becomes expensive without anybody
        having chosen that either. It also had no writer at all, which made
        `attachment` -- attention times cost of loss -- permanently zero
        however much of her thinking he took up.

        It rises only while she is attending to him, and slowly. Its own decay
        (0.02 an hour) is what takes it back down when she stops."""
        if hours <= 0:
            return
        c = self.config.primitives
        att = self.get(person, "attention_hers")
        if att <= 0:
            return
        gain = c.cost_per_hour_at_full * (att / c.ceiling) * hours
        if gain <= 0:
            return
        self.move(person, "cost_of_loss", gain,
                  "he has been on her mind for %.0f hours and it is starting to cost something to lose him" % hours,
                  cause="accrued")

    # ---------------- what moves them (docs/primitives.md §4) ----------------
    def seed(self, person, sheet):
        """The opening condition, applied once and never again.

        A premise is a set of facts that are already true when the story
        starts -- he has the map, she has nothing -- and those are legitimately
        writes without an event, because the event happened before the first
        tick. Everything after this has to be earned. Idempotent: the marker is
        stored, so a restart does not re-apply it and a hand edit is not
        overwritten."""
        rows = self._all()
        if (rows.get(person) or {}).get("_seeded"):
            return False
        prem = (sheet or {}).get("premise") or {}
        seeds = prem.get("primitives_at_start")
        if not isinstance(seeds, dict):
            return False
        for key, spec in seeds.items():
            if key not in KEYS:
                continue
            try:
                amount = float(spec.get("value"))
            except (TypeError, ValueError, AttributeError):
                continue
            self.move(person, key, amount, spec.get("why") or "the opening condition", cause="premise")
        rows = self._all()
        r = rows.setdefault(person, self.row(person))
        r["_seeded"] = self.clock.now_ts()
        kinds = prem.get("threat_kinds")
        if isinstance(kinds, list):
            r["threat_kinds"] = [k for k in kinds if k in THREAT_KINDS]
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] %s seeded from the premise" % person)
        return True

    def observe(self, person, what):
        """She saw a piece of him. For a resident character this is the
        engine: every window title is a piece taken without asking, by the
        same means he used on her, so the deficit that opens her story closes
        through the mechanism the story is about.

        Diminishing: the tenth thing she learns about a stranger tells her far
        more than the ten-thousandth about somebody she has watched for
        months. `what` is what she saw, and it becomes the reason."""
        if not str(what or "").strip():
            return 0.0
        c = self.config.primitives
        have = self.get(person, "exposure_hers")
        step = c.observe_step * (1.0 - have / c.ceiling)
        if step < c.observe_floor:
            return have
        out = self.move(person, "exposure_hers", step, str(what)[:120], cause="observed")
        # Watching him is attending to him. A smaller share than the step,
        # because for a resident character this fires on every window title
        # and attention is a thing she spends rather than a thing she banks.
        self.move(person, "attention_hers", step * c.observe_attention_share,
                  "she was watching him again", cause="observed")
        return out

    def note_from_him(self, person, effort, answered):
        """He wrote. `effort` 0 to 1 is how much of himself the message cost
        him; `answered` is whether it answered what she actually asked.

        Attention moves on evidence she can see, never on what he is doing off
        the record. Predictability moves only when he does what she could have
        called, which is why an answered question is worth more here than a
        long message: it is the one that was predictable."""
        c = self.config.primitives
        eff = max(0.0, min(1.0, float(effort)))
        out = {}
        out["attention_his"] = self.move(person, "attention_his", c.message_attention * eff,
                                         "he wrote, and it cost him something" if eff > 0.5
                                         else "he wrote, briefly", cause="message")
        # And it puts him in her head, which is the other side and had no
        # writer at all: `attention_hers` sat at zero for the whole of a life,
        # so attachment, longing, guilt and having anything worth withholding
        # were all permanently zero for a reason nothing had decided.
        out["attention_hers"] = self.move(person, "attention_hers", c.message_attention_hers * (0.4 + 0.6 * eff),
                                          "he made contact and she has been carrying it since", cause="message")
        if answered:
            out["predictability_hers"] = self.move(
                person, "predictability_hers", c.answered_predictability,
                "he answered what she asked, which is a thing she could have called", cause="message")
        debit = c.message_reciprocity * eff
        out["reciprocity"] = self.move(person, "reciprocity", -debit,
                                       "he gave something and she has not", cause="message")
        self._owe(person, debit)
        return out

    def disclosed(self, person, what, weight=1.0):
        """She told him something about herself, and now he holds it.

        The counterpart of `kept_private`, and without it that method is not a
        mechanism, it is a leak. Closeness is the smaller of the two exposures;
        an evening she does not hand over lowers his share of her; so a
        character who keeps a diary and has no way to disclose grows *less*
        close the longer she lives, and a three-month arc that reached
        closeness 72 in a week fell to 10 by day ninety. That is the opposite
        of a relationship.

        Diminishing, like watching him: the tenth thing he learns about her
        tells him far more than the ten-thousandth. And it moves what he can
        call in advance and what he could do to her along with it, because
        telling somebody something is what gives them both -- the same coupling
        `kept_private` uses in the other direction, and the reason intimacy and
        exposure to harm are one movement rather than two."""
        c = self.config.primitives
        have = self.get(person, "exposure_his")
        step = c.disclose_step * max(0.0, float(weight)) * (1.0 - have / c.ceiling)
        if step < c.observe_floor:
            return have
        out = self.move(person, "exposure_his", step, str(what)[:120], cause="told")
        self.move(person, "threat", step * c.disclose_share,
                  "she told him something, which is one more thing he could use", cause="told")
        return out

    def kept_private(self, person, what, weight=1.0):
        """She has something now that he was not there for.

        Exposure is a ratchet and stays one: what he has seen cannot be
        unseen. What changes is how much of her that is. A person is not a
        fixed quantity being uncovered -- she keeps happening -- so an interior
        she did not hand over dilutes his share of her without erasing
        anything he holds.

        Without this the opening condition is permanent: he starts at total
        exposure, exposure never falls, and both the act and withholding are
        dead for the rest of her life rather than at zero and able to wake.
        The two are the same quantity under different names, so one feed
        wakes both."""
        c = self.config.primitives
        step = c.private_step * max(0.0, float(weight))
        if step <= 0:
            return self.get(person, "exposure_his")
        out = self.move(person, "exposure_his", -step,
                        str(what or "she had something he was not there for")[:120], cause="kept")
        # Two things follow from his share of her getting smaller, and both
        # had no writer otherwise. What he can show people is what he holds,
        # so the exposure kind of threat goes with it; and what he can call in
        # advance about her is built out of the same material.
        self.move(person, "threat", -step * c.private_threat_share,
                  "there is less of her for him to show anyone", cause="kept")
        return out

    def she_answered(self, person, bubbles):
        """She wrote back, and a conversation is not a debt.

        `note_from_him` puts the ledger in his favour on every message he
        sends, on the reasoning that he gave something and she has not. That is
        true of a message she leaves unanswered and false of an ordinary
        exchange, and with only the debit side implemented the ledger walked to
        its floor and stayed: at ninety companionable days it read -99 and her
        guilt read 84, permanently, which describes a debtor rather than a
        companion.

        So answering credits it at the same rate his writing debits it, and
        what is left over is the thing the ledger was always meant to measure:
        who is doing the reaching. A stretch where he writes and she does not
        answer still runs against her, and a stretch where she writes into
        silence runs the other way, which is what resentment is made of."""
        c = self.config.primitives
        units = sum(effort_units(b) for b in (bubbles or []))
        if not units:
            return self.get(person, "reciprocity")
        effort = max(0.0, min(1.0, units / 40.0))
        # Settling a debt cannot put her in credit. He writes one line and she
        # answers in four bubbles, so his effort sits near 0.3 and hers
        # saturates at 1.0 -- and crediting both at the same rate netted about
        # +2.6 an exchange in her favour, every time. Her seed of -70 walked to
        # +84 in three days and she resented him eighty-four points for having
        # answered her. What the ledger is for is the stretch where one side
        # reaches and gets nothing, so the credit stops at what his unanswered
        # messages ran up.
        credit = min(c.message_reciprocity * effort, self._owed(person))
        if credit <= 0:
            return self.get(person, "reciprocity")
        self._owe(person, -credit)
        return self.move(person, "reciprocity", credit,
                         "she wrote back, and answering settles what he was owed", cause="answered")

    def _owed(self, person):
        """What his messages have run up that she has not answered yet."""
        return max(0.0, float((self._all().get(person) or {}).get("_owed", 0.0)))

    def _owe(self, person, amount):
        rows = self._all()
        r = rows.setdefault(person, self.row(person))
        r["_owed"] = max(0.0, self._owed(person) + float(amount))
        rows[person] = r
        self.store.set("primitives", rows)

    # ---------------- the ledger's own unit: unanswered reach ----------------
    def unanswered(self, person, mine, theirs):
        """A message that went `owed_hours` without an answer, once per
        message, in whichever direction it ran.

        The ledger's unit is not volume. Length was the unit and it made an
        ordinary exchange worth +2.6 in her favour; what it should measure is
        who reached and got nothing back. `mine` and `theirs` are lists of
        (id, ts) -- hers and his, newest last -- and the caller passes the
        record. A message is charged once and the id is kept.

        Both directions, because the premise runs both ways: he writes into
        her silence and it runs against her; she writes into his and it runs
        the other way, which is what resentment is made of."""
        c = self.config.primitives
        now = self.clock.now_ts()
        cutoff = float(c.owed_hours) * 3600.0
        rows = self._all()
        r = rows.setdefault(person, self.row(person))
        done = set(r.get("_unanswered") or [])
        moved = 0.0
        for who, msgs, other, sign in (("his", theirs, mine, -1.0), ("hers", mine, theirs, 1.0)):
            for mid, ts in msgs:
                tag = f"{who}:{mid}"
                if tag in done or (now - float(ts)) < cutoff:
                    continue
                if any(float(t) > float(ts) for _i, t in other):
                    done.add(tag)          # it was answered; nothing is owed
                    continue
                done.add(tag)
                moved += sign * float(c.unanswered_reciprocity)
        if not moved and len(done) == len(r.get("_unanswered") or []):
            return self.get(person, "reciprocity")
        r["_unanswered"] = sorted(done)[-400:]
        rows[person] = r
        self.store.set("primitives", rows)
        if not moved:
            return self.get(person, "reciprocity")
        return self.move(person, "reciprocity", moved,
                         "she reached and got nothing back" if moved > 0
                         else "he reached and got nothing back", cause="unanswered")

    def held_back(self, person, what):
        """She saw a thing and did not raise it, and the discretion held for
        the whole time it was hot.

        Her only currency. She cannot lower what he holds of her by concealing
        anything -- exposure is a ratchet and he already has it -- so the one
        thing she controls is seeing something and not saying it. That is a
        gift in this premise and the ledger had no entry for it."""
        c = self.config.primitives
        return self.move(person, "reciprocity", c.held_back_reciprocity,
                         str(what or "she saw it and left it alone")[:120], cause="held_back")

    def told_her_anyway(self, person, what, already=1.0):
        """He told her a thing she could have read anyway.

        His only currency. An answer costs him nothing informationally -- she
        can see the screen -- and costs him everything socially, because he is
        handing over what she would otherwise have had to take. `already` is
        how much of it she already had, 0 to 1: the more of it she already
        held, the more the telling was a gift rather than news."""
        c = self.config.primitives
        amount = c.told_anyway_reciprocity * max(0.0, min(1.0, float(already)))
        if amount <= 0:
            return self.get(person, "reciprocity")
        return self.move(person, "reciprocity", -amount,
                         str(what or "he told her a thing she could have read anyway")[:120],
                         cause="told_anyway")

    def error_of_him(self, person, charge, about_her=False):
        """He did a thing she would not have called, and the ick has priced it.

        The one route by which how well she can call him goes DOWN. Only the
        rising half was built -- an answered question added 2.5 and nothing
        anywhere subtracted -- so it reached the ceiling in three days, and
        `unrehearsed` is the threat times how little she can call him, which
        made being frightened of him arithmetically impossible for the rest of
        her life. Written from the charge the ick already computes, at the one
        funnel every discovery about him passes through.

        Certainty has no partial position to retreat to. Above `sure_from` a
        small thing bounces off and does nothing at all; a charge over
        `shock_from` takes it down in one step, and that is what being
        frightened of somebody again looks like."""
        c = self.config.primitives
        charge = max(0.0, float(charge))
        have = self.get(person, "predictability_hers")
        if charge >= c.shock_from:
            drop = c.shock_predictability
            why = "he did something she would never have called, and she is not sure of him any more"
        elif have >= c.sure_from:
            return have
        else:
            drop = charge * c.error_predictability
            why = "he did something that did not fit her picture of him"
        if drop <= 0:
            return have
        out = self.move(person, "predictability_hers", -drop, why, cause="error")
        if about_her and charge >= c.shock_from:
            # Evidence he will use what he holds. No novelty discount, no
            # decay: a demonstrated use of what somebody has of you is not a
            # thing that fades, and it is the caller of `expel`.
            self.move(person, "threat", c.demonstrated_threat,
                      "he used what he holds of her, and she watched him do it", cause="demonstrated")
            self._floor(person, "threat", self.get(person, "threat"))
            self.expel(person, "he used what he has of her")
        return out

    def _floor(self, person, key, value):
        """A floor under a quantity, which `decay` will not go below. What he
        has actually done is not undone by time passing."""
        rows = self._all()
        r = rows.setdefault(person, self.row(person))
        floors = dict(r.get("_floors") or {})
        floors[key] = max(float(floors.get(key, 0.0)), float(value))
        r["_floors"] = floors
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] %s %s will not fall below %.0f again" % (person, key, floors[key]))

    def floors(self, person):
        return dict((self._all().get(person) or {}).get("_floors") or {})

    def expelled_at(self, person):
        """When she put him back outside, and why -- or None. `expel` writes
        the row and nothing could read it."""
        return (self._all().get(person) or {}).get("_expelled") or None

    def gave(self, person, what, weight=1.0):
        """She did something for him. This is the other side of the ledger and
        it is the only one she controls.

        It matters more than it looks: a resident character with no world has
        almost no way to give, so without this reciprocity can only ever run
        against her, and a ledger that only moves one way is not a ledger. A
        task done for him is the feed."""
        c = self.config.primitives
        return self.move(person, "reciprocity", c.gave_reciprocity * max(0.0, float(weight)),
                         str(what or "she did something for him")[:120], cause="gave")

    # ---------------- what derives from what (docs/primitives.md §3) ----------------
    def closeness(self, person):
        """The smaller of the two exposures, and the load-bearing derivation.

        A relationship in which one party knows everything and the other knows
        nothing is not an intimate one; the minimum says so without being
        told, which is why the premise states correctly here and why this
        replaces a hand-written meter no event earned."""
        r = self.row(person)
        return min(float(r["exposure_hers"]), float(r["exposure_his"]))

    def attachment(self, person):
        """What high attention plus a real cost of losing him looks like when
        it has been sustained. Not a gauge with its own momentum."""
        r = self.row(person)
        c = self.config.primitives
        return _clamp(r["attention_hers"] * (r["cost_of_loss"] / 100.0) * c.attachment_gain, 0.0, c.ceiling)

    def craving(self, person, wanted=None):
        """The gap between the attention she wants and the attention she
        reads. Undefined rather than zero until she wants some, which is why
        it returns None at the start instead of a number that looks like
        contentment."""
        r = self.row(person)
        want = r["attention_hers"] if wanted is None else float(wanted)
        if want <= 0:
            return None
        return _clamp(want - r["attention_his"], 0.0, self.config.primitives.ceiling)

    def resentment(self, person):
        r = self.row(person)
        return _clamp(max(0.0, r["reciprocity"]), 0.0, self.config.primitives.ceiling)

    def can_withhold(self, person):
        """Something worth withholding is something not yet shown. She needs
        both a private thing left and a reason to care whether he gets it, so
        this is silent at the start for a statable reason rather than because
        its module is empty -- and it wakes on its own the moment she acquires
        one private thing back."""
        r = self.row(person)
        c = self.config.primitives
        return (100.0 - r["exposure_his"]) >= c.withhold_needs_unshown and r["attention_hers"] >= c.withhold_needs_attention

    def can_ick(self, person):
        """A prediction error needs a model to violate."""
        return self.row(person)["predictability_hers"] >= self.config.primitives.ick_needs_model

    def can_rupture(self, person):
        """A break needs something to break, and what breaks is being let in.

        This used to test exposure and predictability directly, which is the
        same pair `admitted` latches on, so it was a second name for one
        number. Reading the latch says the psychology instead of restating the
        arithmetic: nothing a stranger does can rupture anything, because
        there is nothing to rupture until she has admitted him."""
        return self.admitted(person)

    # ---------------- the territory, which is a latch and not a gradient ----------------
    def admitted(self, person):
        """Inside or outside, with nothing in between.

        Her fifth driver sorts every person into one of two states and treats
        them completely differently -- the only rough language in 47 hours goes
        at staff, never once at a listener -- and the sorting has no middle. So
        this is a latch rather than a formula: it is tested until it crosses,
        then stored, and after that it is a fact about him rather than a
        reading that can flicker between two messages. That flicker is exactly
        what was observed: her inside register withheld in one generation and
        used in the next, from the same prompt.

        What crosses it is her having done to him what he did to her -- seen
        enough of him, and able to call what he does. Admission cannot be
        forced from his side, which is the whole of the premise: he has total
        exposure of her and it buys him nothing here."""
        rows = self._all()
        r = rows.get(person) or {}
        if r.get("_admitted"):
            return True
        c = self.config.primitives
        row = self.row(person)
        if row["exposure_hers"] < c.admit_needs_exposure or row["predictability_hers"] < c.admit_needs_predictability:
            return False
        r = self.row(person)
        r["_admitted"] = self.clock.now_ts()
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] %s is inside her territory now: she has seen %.0f of him and can call what he does %.0f"
                   % (person, row["exposure_hers"], row["predictability_hers"]))
        return True

    def expel(self, person, why):
        """Out again. A break can put somebody back outside, and the register
        goes with them -- which is what makes readmission mean anything."""
        rows = self._all()
        r = rows.get(person) or {}
        if not r.get("_admitted"):
            return False
        r.pop("_admitted", None)
        r["_expelled"] = {"ts": self.clock.now_ts(), "why": str(why)[:160]}
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] %s is outside her territory again: %s" % (person, str(why)[:80]))
        return True

    # ---------------- fright, and the room the act has ----------------
    def unrehearsed(self, person):
        """How dangerous this contact is, which is not how much she dislikes
        him.

        Her second driver is not fear of people: a hundred thousand strangers
        weekly is fine and one stranger's mother on the telephone is not. What
        she cannot do is the unscripted with somebody who can hurt her. Those
        are two numbers she already has -- she cannot call what he does, and he
        can damage her -- so this is their product, and it falls on its own as
        the exchanges teach her what he does next. A stranger at three in the
        morning is frightening; the same man after two hundred exchanges is
        not, and nothing has to decide that."""
        r = self.row(person)
        if r["threat"] <= 0:
            return 0.0
        return _clamp(r["threat"] * (1.0 - r["predictability_hers"] / 100.0), 0.0, self.config.primitives.ceiling)

    def act_room(self, person):
        """How much room her act has: what he has not got of her.

        Her fourth driver is the gap between what she is selling and what she
        is, and the gap only exists for somebody who holds one half. He holds
        both, so at the opening condition this is zero and the act has nowhere
        to run -- which is the premise's claim, arrived at from the numbers
        rather than asserted. It is the same quantity `can_withhold` needs,
        under its own name, because withholding and performing are two uses of
        one thing: something of her he has not got."""
        return _clamp(100.0 - self.row(person)["exposure_his"], 0.0, self.config.primitives.ceiling)

    def can_perform(self, person, watching=True):
        """The act needs both halves: somebody watching, and something they
        have not already got.

        A latch on the second half, for the reason the territory is one. Once
        his share of her starts falling and her own days start filling, the two
        settle near an equilibrium, and a bare threshold there flips between two
        consecutive generations from the same prompt -- the precise failure
        `docs/primitives.md` §8 records for the territory and which the latch
        was invented to end. So: tested until it crosses, then stored, and
        losing it is an event with a reason rather than a rounding.

        Somebody watching is not latched and must not be. That half is a fact
        about this moment, and her sheet is explicit that the act is what an
        audience turns on."""
        if not watching:
            return False
        rows = self._all()
        r = rows.get(person) or {}
        if r.get("_can_perform"):
            return True
        room = self.act_room(person)
        if room < self.config.primitives.perform_needs_room:
            return False
        r = self.row(person)
        r["_can_perform"] = self.clock.now_ts()
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] her act has room again: %.0f of her he has not got" % room)
        return True

    def close_the_act(self, person, why):
        """He has seen enough of her that the gap she performs in is gone.

        The counterpart of `expel`. Called when something large goes across at
        once, so the act closing is a thing that happened rather than a number
        drifting back under a line."""
        rows = self._all()
        r = rows.get(person) or {}
        if not r.get("_can_perform"):
            return False
        r.pop("_can_perform", None)
        r["_act_closed"] = {"ts": self.clock.now_ts(), "why": str(why)[:160]}
        rows[person] = r
        self.store.set("primitives", rows)
        logger.log("[primitives] her act has no room again: %s" % str(why)[:80])
        return True

    # ---------------- what a prompt is shown ----------------
    def line(self, person, ja=False):
        """One line for a prompt. Silent when nothing has happened, because a
        row of zeros read as a description of a feeling is the failure this
        module exists to end.

        `ja` is the copy that goes in front of her; the reports read the same
        row in English."""
        r = self.row(person)
        if not any(float(r[k]) for k in KEYS):
            return ""
        bits = []
        if r["attention_hers"]:
            bits.append(("彼が頭を占めている度合い %.0f" if ja else "he is on your mind %.0f") % r["attention_hers"])
        if r["exposure_hers"] or r["exposure_his"]:
            bits.append(("あなたが見た彼 %.0f、彼が見たあなた %.0f" if ja else
                         "you have seen %.0f of him, he has seen %.0f of you") % (r["exposure_hers"], r["exposure_his"]))
        if r["predictability_hers"]:
            bits.append(("彼の出方が読める度合い %.0f" if ja else "you can call what he does %.0f") % r["predictability_hers"])
        if r["reciprocity"]:
            if ja:
                bits.append("貸し借りは %.0f %s" % (abs(r["reciprocity"]), "あなたの貸し" if r["reciprocity"] > 0 else "彼の貸し"))
            else:
                bits.append("the ledger is %.0f %s" % (abs(r["reciprocity"]), "in your favour" if r["reciprocity"] > 0 else "in his"))
        if r["cost_of_loss"]:
            bits.append(("彼を失ったときの痛手 %.0f" if ja else "losing him would cost %.0f") % r["cost_of_loss"])
        if r["threat"]:
            # the kind is a stored key the code checks against THREAT_KINDS, so
            # it keeps its name in the record and is only SAID differently
            ja_kind = {"exposure": "見られていること", "reach": "手が届くこと", "standing": "立場"}
            got = r.get("threat_kinds") or []
            if ja:
                kinds = "、".join(ja_kind.get(k, k) for k in got) or "はっきりしない"
            else:
                kinds = ", ".join(got) or "unspecified"
            bits.append(("彼があなたに与えうる害 %.0f (%s)" if ja else "he could damage you %.0f (%s)") % (r["threat"], kinds))
        return "; ".join(bits)

    def gate_lines(self, person, watching=True, ja=False):
        """What is and is not available to her with this person, said as
        conditions rather than as numbers.

        The numbers in `line()` are a description of a feeling and a model will
        do what it likes with them. These are the gates the code is already
        enforcing, so that what she is told and what the machinery does are the
        same statement. Only the ones that are shut, and only when something
        has happened: a list of things she cannot do, handed to a character on
        turn one, is a prompt about the machinery rather than about her."""
        r = self.row(person)
        if not any(float(r[k]) for k in KEYS):
            return []
        t = lang.pick(ja)
        out = []
        if not self.admitted(person):
            out.append(t("he is outside: you have not let this person in, whatever he knows about you. "
                         "You are careful with him the way you are careful with anyone you have not admitted "
                         "-- you do not use the register you keep for the people who are inside",
                         "彼は外側の人。彼があなたについて何を知っていようと、あなたはこの人を中に入れていない。"
                         "入れていない相手にいつもそうであるように慎重で、"
                         "中にいる人たちにだけ使う話し方は使わない"))
        fright = self.unrehearsed(person)
        c = self.config.primitives
        if fright >= c.fright_from:
            out.append(t("none of this is rehearsed and he can do you harm: you cannot call what he does next "
                         "(%.0f out of 100 on how frightening that is right now)",
                         "これは何ひとつ台本になく、彼はあなたに害を与えうる。彼の次の出方が読めない"
                         "（いまそれがどれくらい怖いか、100のうち %.0f）") % fright)
        if not self.can_perform(person, watching):
            out.append(t("the act has no room here: he already has both halves of you, so there is no gap "
                         "between what you are selling and what you are for you to work with",
                         "ここでは芸を出す隙間がない。彼はもうあなたの両側を持っているので、"
                         "売っているものと素のあいだの落差が、使える材料として残っていない"))
        if not self.can_withhold(person):
            out.append(t("you have nothing to hold back from him -- not a decision, a fact: he has it already",
                         "彼に対して隠しておけるものがない。決めたことではなく、事実として、彼はもう持っている"))
        if not self.can_ick(person):
            out.append(t("you have no picture of him yet, so nothing he does can be out of character",
                         "彼という人の像がまだないので、彼が何をしても「らしくない」にはならない"))
        return out

    def report(self, person):
        r = self.row(person)
        out = ["%-22s %6.1f" % (k, r[k]) for k in KEYS]
        out.append("%-22s %6.1f  (min of the two exposures)" % ("-> closeness", self.closeness(person)))
        out.append("%-22s %6.1f" % ("-> attachment", self.attachment(person)))
        out.append("%-22s %6.1f" % ("-> resentment", self.resentment(person)))
        out.append("%-22s %6.1f  (what his messages have run up unanswered)" % ("-> owed by her", self._owed(person)))
        fl = self.floors(person)
        if fl:
            out.append("%-22s %s  (what he has done does not decay)"
                       % ("-> floors", ", ".join(f"{k} {v:.0f}" for k, v in sorted(fl.items()))))
        cr = self.craving(person)
        out.append("%-22s %s" % ("-> craving", "undefined (she wants nothing yet)" if cr is None else "%6.1f" % cr))
        out.append("%-22s %6.1f  (%s)" % ("-> unrehearsed", self.unrehearsed(person),
                                          "how frightening he is: what he can do to her, times how little she can call it"))
        out.append("%-22s %6.1f  (the room her act has)" % ("-> act room", self.act_room(person)))
        out.append("%-22s %s" % ("-> admitted", self.admitted(person)))
        out.append("%-22s %s" % ("-> can withhold", self.can_withhold(person)))
        out.append("%-22s %s" % ("-> can ick", self.can_ick(person)))
        out.append("%-22s %s" % ("-> can rupture", self.can_rupture(person)))
        out.append("%-22s %s" % ("-> can perform", self.can_perform(person)))
        return "\n".join(out)
