"""Every check the project runs, in one table, read off the tools themselves.

`tools/smoke.py` runs before every restart and refuses one if it fails; it
carries about thirty checks, each announced by a `[smoke]` line in its
source, and half of them are other tools it runs as subprocesses. Beside it
are thirty `tools/*_test.py` harnesses that are run by hand. Nothing listed
them: to know what was guarded you read smoke's 750 lines, and a new check
went in wherever the last one was.

This reads them and writes `docs/checks.md`: one row per smoke check in the
order smoke runs them (its heading, the tool it runs if any, and whether a
failure stops a restart or is only reported), then one row per hand-run tool
with the first line of its docstring. Generated; edit the tools, not the
table. `tools/docs_check.py` resolves every path in it, so a row that names
a tool that has been deleted fails the docs pass.

    python tools/checks_index.py            # writes docs/checks.md
    python tools/checks_index.py --print    # to stdout only
"""
import argparse
import ast
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
if (sys.stdout.encoding or "").lower().replace("-", "") != "utf8":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", line_buffering=True)

OUT = os.path.join("docs", "checks.md")
SMOKE = os.path.join("tools", "smoke.py")
_HEAD = re.compile(r'print\(\s*f?"\[smoke\] (.*?)"\s*\)')
_TOOL = re.compile(r'os\.path\.join\("tools",\s*"([a-z_]+\.py)"\)')


def _docline(path):
    try:
        with open(path, encoding="utf-8") as fh:
            d = ast.get_docstring(ast.parse(fh.read())) or ""
    except (OSError, SyntaxError):
        return ""
    line = d.strip().split("\n")[0].strip()
    # a date inside a quoted docstring is the tool's, not a dated note of this
    # document's; the docs check would otherwise send it to HISTORY
    return re.sub(r"\b\d{4}-\d{2}-\d{2}\b", "(dated)", line)


def smoke_rows():
    """(heading, tool, stops-a-restart) per `[smoke]` announcement, in order.

    The block after a heading runs to the next heading; a tool named in it is
    the subprocess it runs; `failures.append` in it means a failure stops a
    restart, and its absence means the check is reported only."""
    with open(SMOKE, encoding="utf-8") as fh:
        src = fh.read()
    # a `[smoke]` line with a brace in it is a progress line (the copy of the
    # save), not a check
    heads = [(m.start(), m.group(1)) for m in _HEAD.finditer(src) if "{" not in m.group(1)]
    rows = []
    for i, (pos, head) in enumerate(heads):
        end = heads[i + 1][0] if i + 1 < len(heads) else len(src)
        block = src[pos:end]
        tools = sorted(set(_TOOL.findall(block)))
        stops = "failures.append" in block or "return 1" in block
        rows.append((head, tools, stops))
    return rows


def hand_rows():
    out = []
    for f in sorted(os.listdir("tools")):
        if f.endswith("_test.py") or f in ("sweep.py", "existence_matrix.py", "fills_check.py", "isolation.py",
                                           "blank_paths.py", "character_test.py", "ready_test.py", "registry.py"):
            p = os.path.join("tools", f)
            out.append((p.replace("\\", "/"), _docline(p)))
    return out


def render():
    lines = ["# The checks, in one table", "",
             "<!-- doc: generated by tools/checks_index.py; edit the tools, not this file -->", "",
             "What `tools/smoke.py` runs before every restart, in the order it runs it, and",
             "what is run by hand. A check that *stops* fails smoke and refuses the restart; one",
             "that is *reported* prints and goes on. The tool column is the subprocess the check",
             "runs, where it is one; the rest are inline in smoke.", "",
             "## Smoke, in order", "",
             "| # | the check | tool | on failure |", "|---|---|---|---|"]
    for n, (head, tools, stops) in enumerate(smoke_rows(), 1):
        tool = ", ".join(f"`tools/{t}`" for t in tools) if tools else ""
        lines.append(f"| {n} | {head} | {tool} | {'stops' if stops else 'reported'} |")
    lines += ["", "## Run by hand", "",
              "Each builds the App on a copy of a save, or reads the tree, and spends nothing",
              "unless its docstring says so.", "",
              "| tool | what it checks |", "|---|---|"]
    for p, d in hand_rows():
        lines.append(f"| `{p}` | {d} |")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--print", action="store_true", help="stdout only, write nothing")
    args = ap.parse_args(argv)
    text = render()
    if args.print:
        print(text)
        return 0
    old = ""
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as fh:
            old = fh.read()
    if old != text:
        with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {OUT}: {len(smoke_rows())} smoke checks, {len(hand_rows())} hand-run tools")
    else:
        print(f"{OUT} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
